"""Run all experiments. Write results/RESULTS.md and one CSV per experiment.

    py run_all.py            use the local copy of the Eurostat data
    py run_all.py --refresh  download the data again
"""
from __future__ import annotations

import csv
import sys
from datetime import date
from pathlib import Path

from experiments import e1_mapping, e2_visibility, e3_stability, e4_sensitivity

OUT = Path(__file__).resolve().parent / "results"


def main() -> None:
    refresh = "--refresh" in sys.argv
    OUT.mkdir(exist_ok=True)
    parts = [f"# Results\n\nGenerated by `run_all.py` on {date.today().isoformat()}. "
             "Do not edit this file by hand. All numbers come from the scripts in `experiments/`."]
    for module in (e1_mapping, e2_visibility, e3_stability, e4_sensitivity):
        text, table = module.run(refresh)
        parts.append(text)
        name = module.__name__.split(".")[-1]
        with open(OUT / f"{name}.csv", "w", newline="", encoding="utf-8") as handle:
            csv.writer(handle).writerows(table)
    (OUT / "RESULTS.md").write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {OUT / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
